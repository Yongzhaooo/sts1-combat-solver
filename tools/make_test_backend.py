"""Generate the test-only backend used while another class is still in progress.

The production backend is the single source of truth. Copying it does not hold:
the copy drifts the moment `backend.py` changes, which is exactly how the live
Defect import once broke. This writes a thin shim that imports the real backend,
opens the class gate on that module and serves through it, so there is nothing
left to drift.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "overlay" / "backend_defect_test.py"

SHIM = '''"""TEST BUILD ONLY — generated by tools/make_test_backend.py, do not edit.

`overlay/build.py --defect-test` points `backend=` at this file so the Defect can
be played before the character gate opens. It imports the real backend and opens
the gate on that module, so it cannot drift from `backend.py`.
"""
import backend

backend.SUPPORTED_CLASSES = {'IRONCLAD': '战士', 'DEFECT': '机器人'}  # TEST BUILD ONLY

if __name__ == '__main__':
    backend.serve()
'''


def main():
    TARGET.write_text(SHIM, encoding="utf-8")
    print("wrote", TARGET)


if __name__ == "__main__":
    main()
